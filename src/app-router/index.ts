/**
 * File based router with Next.js App Router conventions:
 * page, layout, loading, error, not-found, route (API), socket (WebSocket),
 * middleware, metadata, revalidate and form actions.
 *
 *   app.use(await appRouter({ dir: './app' }))
 */
import { existsSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { Raiko } from '../app'
import { HttpError } from '../error'
import { jsx, Suspense, renderToString, renderStream, hasSuspense, type Child } from '../jsx/runtime'
import { als, RedirectSignal, type RequestStore, type PageUser } from '../server/request-store'
import { PREFETCH_SCRIPT } from '../components'
import { mergeMetadata, metadataToHtml, type Metadata } from './metadata'
import { scanApp, scanFiles, type Segment } from './scan'
import { devErrorPage, devOverlay, devToolsHtml } from './dev-error'
import { formToObject } from '../body'
import type { BaseContext } from '../context'

export type { Metadata }

export interface AppRouterOptions {
  /** folder with your pages, default ./app */
  dir?: string
  /** folder served at / for static files, default ./public */
  publicDir?: string
  /** inject Voodoo.js when a page uses v-* directives. true by default */
  voodoo?: boolean | { src: string }
  /** detailed error pages, default true unless NODE_ENV=production */
  dev?: boolean
  /** supported locales; the first one is the default. Enables /:locale prefixes */
  locales?: string[]
  /**
   * Modules keyed by path relative to the app folder, generated by `raiko build`.
   * With a manifest nothing is read from disk, so it runs on Vercel and Workers.
   */
  manifest?: Record<string, Record<string, any>>
  /** public URL, used for sitemap.xml and canonical links. Defaults to APP_URL */
  siteUrl?: string
  /** a11ymedic "Check this page" button in development. Default: same as dev */
  a11y?: boolean
  /**
   * Who is signed in. Pages and layouts that `export const auth = true` or
   * `export const roles = ['admin']` are only rendered for matching users.
   */
  getUser?: (ctx: any) => PageUser | null | undefined | Promise<PageUser | null | undefined>
  /** where signed out users go, default /login (callbackUrl is added) */
  signIn?: string
}

const VOODOO_SRC = 'https://cdn.jsdelivr.net/npm/voodoojs@1.1.0/dist/voodoo.full.min.js'
const VOODOO_RE = /\s(v-(data|on|bind|model|show|if|for|text|html|class)[\s=:>])/

type Mod = Record<string, any>
const load = async (file: string): Promise<Mod> => import(pathToFileURL(file).href)

export interface PageProps<P = Record<string, string | string[]>> {
  params: P
  searchParams: Record<string, string | string[]>
  actionData?: unknown
}

export async function appRouter(options: AppRouterOptions = {}): Promise<Raiko> {
  const dir = resolve(options.dir ?? 'app')
  const manifest = options.manifest
  if (!manifest && !existsSync(dir))
    throw new Error(`error[RK0100]: app directory not found: ${dir}\n  = help: create ${dir}/page.tsx or pass appRouter({ dir })`)
  // detailed errors only when explicitly developing: an unset NODE_ENV in production must not leak source
  const dev = options.dev ?? (typeof process !== 'undefined' && (process.env?.NODE_ENV === 'development' || process.env?.RAIKO_DEV === '1'))
  const voodooSrc = options.voodoo === false ? null : typeof options.voodoo === 'object' ? options.voodoo.src : VOODOO_SRC
  const a11y = options.a11y ?? dev
  const siteUrl = (options.siteUrl ?? (typeof process !== 'undefined' ? process.env?.APP_URL : undefined) ?? '').replace(/\/$/, '')
  const segments = manifest ? scanFiles(Object.keys(manifest)) : scanApp(dir)

  // load every module up front: errors show at boot, not on first visit
  const mods = new Map<string, Mod>()
  for (const s of segments)
    for (const f of Object.values(s.files)) if (f && !mods.has(f)) mods.set(f, manifest ? manifest[f]! : await load(join(dir, f)))
  const mod = (f?: string) => (f ? mods.get(f) : undefined)

  const app = new Raiko({ name: 'raiko:app-router' })
  const cache = new Map<string, { body: string; status: number; expires: number }>()

  // middleware.ts next to or inside the app folder
  const mwFromManifest = manifest && (manifest['middleware.ts'] ?? manifest['../middleware.ts'])
  for (const m of mwFromManifest ? ['manifest'] : [join(dir, 'middleware'), join(dir, '..', 'middleware')]) {
    const file = mwFromManifest ? 'manifest' : ['.ts', '.tsx', '.js'].map((e) => m + e).find(existsSync)
    if (!file) continue
    const mw = mwFromManifest || (await load(file))
    const matcher: RegExp | null = mw.config?.matcher ? new RegExp(mw.config.matcher) : null
    // test the matcher against the path without its locale prefix, so /en/admin is guarded like /admin
    const unprefixed = (path: string) => {
      const first = path.split('/')[1] ?? ''
      return options.locales?.includes(first) ? path.slice(first.length + 1) || '/' : path
    }
    app.onBeforeHandle((ctx) => (matcher && !matcher.test(unprefixed(ctx.path)) ? undefined : mw.default(ctx)), 'global')
    break
  }

  // ./public is served whenever it exists, with or without a manifest; hosts without a file system
  // (Workers) simply have no folder there, and their own static assets take over
  const publicDir = resolve(options.publicDir ?? 'public')
  let hasPublic = false
  try {
    hasPublic = existsSync(publicDir)
  } catch {}
  if (hasPublic) {
    const { staticFiles } = await import('../plugins/static')
    app.use(staticFiles({ dir: publicDir, prefix: '/' }))
    const { imageHandler } = await import('./image')
    app.get('/_raiko/image', imageHandler(publicDir))
  }

  const root = segments[0]!
  const nearest = (seg: Segment, kind: 'not-found' | 'error' | 'loading' | 'forbidden' | 'unauthorized') =>
    [...seg.chain].reverse().find((s) => s.files[kind])

  /** auth rules of a page: the page itself wins, otherwise the nearest layout that sets them */
  const ruleFor = (seg: Segment): { auth: boolean; roles: string[] | null } => {
    let roles: string[] | null = null
    let auth = false
    for (const s of seg.chain) {
      const l = mod(s.files.layout)
      if (l?.auth) auth = true
      if (Array.isArray(l?.roles)) (roles = l.roles), (auth = true)
    }
    const p = mod(seg.files.page)
    if (p?.auth === false && !roles) auth = false
    if (p?.auth) auth = true
    if (Array.isArray(p?.roles)) (roles = p.roles), (auth = true)
    return { auth, roles }
  }
  if (!options.getUser && segments.some((s) => s.files.page && ruleFor(s).auth))
    throw new Error('error[RK0110]: a page exports auth or roles, but appRouter has no getUser\n  = help: appRouter({ getUser: async (ctx) => (await auth.getSession(ctx.request))?.user })')

  const userOf = async (ctx: any): Promise<PageUser | null> => {
    if (!options.getUser) return null
    if (ctx.__user === undefined) ctx.__user = (await options.getUser(ctx)) ?? null
    return ctx.__user
  }
  const allowed = (u: PageUser, roles: string[] | null) =>
    !roles || roles.includes(u.role ?? '') || (u.roles ?? []).some((r) => roles.includes(r))

  const makeStore = (ctx: any, params: Record<string, string | string[]>): RequestStore => ({
    request: ctx.request,
    pathname: ctx.path,
    params,
    searchParams: new URL(ctx.request.url).searchParams,
    cookies: ctx.cookie,
    head: [],
    status: 200,
    headers: {},
    locale: (ctx as any).locale,
    user: ctx.__user ?? null,
  })

  const fixParams = (seg: Segment, params: Record<string, string>) => {
    const out: Record<string, string | string[]> = { ...params }
    for (const c of seg.catchAll) out[c] = params[c] ? params[c]!.split('/') : []
    return out
  }

  /** Wrap content in every layout of the chain, inner to outer. */
  const withLayouts = (chain: Segment[], content: Child, params: unknown): Child => {
    let tree = content
    for (let i = chain.length - 1; i >= 0; i--) {
      const layout = mod(chain[i]!.files.layout)
      if (layout?.default) tree = jsx(layout.default, { children: tree, params })
    }
    return tree
  }

  const collectMetadata = async (seg: Segment, page: Mod, props: PageProps) => {
    const list: Metadata[] = []
    for (const s of seg.chain) {
      const l = mod(s.files.layout)
      if (l?.metadata) list.push(l.metadata)
      if (l?.generateMetadata) list.push(await l.generateMetadata(props))
    }
    if (page.metadata) list.push(page.metadata)
    if (page.generateMetadata) list.push(await page.generateMetadata(props))
    return mergeMetadata(list)
  }

  const finishHtml = (html: string, store: RequestStore, meta: Metadata, devInfo: Record<string, unknown> | null = null) => {
    const head = metadataToHtml(meta) + store.head.join('') + `<meta name="generator" content="Raiko.js">`
    if (!/<html[\s>]/i.test(html))
      html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head><body>${html}</body></html>`
    // a layout without <head> still gets its title and meta tags
    if (/<\/head>/i.test(html)) html = html.replace(/<\/head>/i, head + '</head>')
    else html = html.replace(/<html([^>]*)>/i, `<html$1><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">${head}</head>`)
    let tail = PREFETCH_SCRIPT.html + (devInfo ? devToolsHtml(devInfo) : '')
    if (devInfo && a11y) tail += A11Y_SCRIPT
    if (voodooSrc && VOODOO_RE.test(html)) tail += `<script src="${voodooSrc}" defer></script>`
    return html.includes('</body>') ? html.replace(/<\/body>(?![\s\S]*<\/body>)/i, tail + '</body>') : html + tail
  }

  const respond = (body: BodyInit, status: number, store: RequestStore) =>
    new Response(body, { status: store.status !== 200 ? store.status : status, headers: { 'content-type': 'text/html; charset=utf-8', ...store.headers } })

  /** Render a page (or a special file) inside its layouts, handling every error kind. */
  const render = async (seg: Segment, ctx: BaseContext, extra: Partial<PageProps> = {}, forced?: { file: string; status: number; error?: Error }): Promise<Response> => {
    const params = fixParams(seg, ctx.params)
    const store = makeStore(ctx, params)
    return als.run(store, async () => {
      const page = forced ? mod(forced.file)! : mod(seg.files.page)!
      const props: PageProps & { error?: Error } = {
        params,
        searchParams: Object.fromEntries(store.searchParams),
        ...extra,
        ...(forced?.error ? { error: forced.error } : {}),
      }
      try {
        let content: Child = jsx(page.default, props)
        const loading = !forced && nearest(seg, 'loading')
        if (loading) content = jsx(Suspense, { fallback: jsx(mod(loading.files.loading)!.default, {}), children: content })
        const tree = withLayouts(seg.chain, content, params)
        const meta = await collectMetadata(seg, page, props)
        const t0 = Date.now()
        const info = () => ({ route: seg.path, params, status: forced?.status ?? 200, ms: Date.now() - t0, layouts: seg.chain.filter((s) => s.files.layout).length, loading: !!loading, revalidate: page.revalidate ?? null, title: meta.title ?? null })
        if (hasSuspense(tree) || hasSuspense(content)) {
          let shellHasVoodoo = false
          const stream = await renderStream(tree, {
            transformShell: (h) => ((shellHasVoodoo = !!voodooSrc && VOODOO_RE.test(h)), finishHtml(h, store, meta, dev ? info() : null)),
            // content that arrives after the shell can use Voodoo too: add the script once, at the end
            onEnd: (streamedHtml) =>
              voodooSrc && !shellHasVoodoo && VOODOO_RE.test(streamedHtml) ? `<script src="${voodooSrc}" defer></script>` : '',
            onError: async (e) => {
              if (process.env.NODE_ENV !== 'test') console.error(e)
              if (dev) return devOverlay(e as Error, ctx.request)
              const eb = nearest(seg, 'error')
              return eb ? renderToString(jsx(mod(eb.files.error)!.default, { error: e })) : '<p>Something went wrong.</p>'
            },
          })
          return respond(stream, forced?.status ?? 200, store)
        }
        const html = finishHtml(await renderToString(tree), store, meta, dev ? info() : null)
        return respond(html, forced?.status ?? 200, store)
      } catch (err) {
        return renderError(err as Error, seg, ctx, forced)
      }
    })
  }

  const renderError = async (err: Error, seg: Segment, ctx: BaseContext, forced?: { file: string }): Promise<Response> => {
    if (err instanceof RedirectSignal) return new Response(null, { status: err.status, headers: { location: err.location } })
    if (err instanceof HttpError && err.status === 401) {
      const ua = nearest(seg, 'unauthorized')
      if (ua && forced?.file !== ua.files.unauthorized) return render(ua, ctx, {}, { file: ua.files.unauthorized!, status: 401 })
      const back = encodeURIComponent(ctx.path + (new URL(ctx.request.url).search || ''))
      return new Response(null, { status: 307, headers: { location: `${options.signIn ?? '/login'}?callbackUrl=${back}` } })
    }
    if (err instanceof HttpError && err.status === 403) {
      const fb = nearest(seg, 'forbidden')
      if (fb && forced?.file !== fb.files.forbidden) return render(fb, ctx, {}, { file: fb.files.forbidden!, status: 403 })
      return new Response(shell('403: Forbidden', '<h1>403</h1><p>You do not have access to this page.</p>'), { status: 403, headers: { 'content-type': 'text/html; charset=utf-8' } })
    }
    if (err instanceof HttpError && err.status === 404) {
      const nf = nearest(seg, 'not-found')
      if (nf && forced?.file !== nf.files['not-found']) return render(nf, ctx, {}, { file: nf.files['not-found']!, status: 404 })
      return new Response(defaultNotFound(), { status: 404, headers: { 'content-type': 'text/html; charset=utf-8' } })
    }
    if (err instanceof HttpError && err.status < 500) return err.toResponse()
    if (process.env.NODE_ENV !== 'test') console.error(err)
    if (dev) return new Response(devErrorPage(err, ctx.request), { status: 500, headers: { 'content-type': 'text/html; charset=utf-8' } })
    const eb = nearest(seg, 'error')
    if (eb && forced?.file !== eb.files.error) return render(eb, ctx, {}, { file: eb.files.error!, status: 500, error: err })
    return new Response(defaultError(), { status: 500, headers: { 'content-type': 'text/html; charset=utf-8' } })
  }

  const prefixes = options.locales?.length ? ['', '/:locale'] : ['']
  if (options.locales?.length) {
    const locales = options.locales
    app.derive((ctx) => {
      const first = ctx.path.split('/')[1] ?? ''
      return { locale: locales.includes(first) ? first : locales[0]! }
    })
  }

  for (const seg of segments) {
    const routeMod = mod(seg.files.route)
    const pageMod = mod(seg.files.page)
    const socketMod = mod(seg.files.socket)
    for (const prefix of prefixes) {
      const path = (prefix + (seg.path === '/' ? '' : seg.path)) || '/'
      if (routeMod && prefix === '') {
        for (const m of ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'] as const) {
          const fn = routeMod[m]
          if (typeof fn !== 'function') continue
          app.route(m, path, (ctx: any) => als.run(makeStore(ctx, fixParams(seg, ctx.params)), () => fn(ctx)), routeMod.schema?.[m] ?? {})
        }
      }
      if (socketMod?.default && prefix === '') app.ws(path, socketMod.default)
      if (pageMod?.default) {
        const revalidate: number | undefined = pageMod.revalidate
        app.get(path, async (ctx: any) => {
          // '/:locale/...' only matches real locales, anything else is a 404
          if (prefix && !options.locales!.includes(ctx.params.locale)) return renderNotFound(ctx)
          const denied = await guard(seg, ctx)
          if (denied) return denied
          // never cache personalized requests, key on path and query, bounded size
          const personal = ctx.request.headers.has('cookie') || ctx.request.headers.has('authorization')
          const key = ctx.path + '?' + new URL(ctx.request.url).searchParams.toString()
          if (revalidate && !personal) {
            const hit = cache.get(key)
            if (hit && hit.expires > Date.now())
              return new Response(hit.body, { status: hit.status, headers: { 'content-type': 'text/html; charset=utf-8', 'x-raiko-cache': 'HIT' } })
          }
          const res = await render(seg, ctx)
          if (revalidate && !personal && res.status === 200 && !res.headers.has('set-cookie')) {
            const body = await res.text()
            if (cache.size >= 1000) {
              const now = Date.now()
              for (const [k, v] of cache) if (v.expires <= now) cache.delete(k)
              if (cache.size >= 1000) cache.delete(cache.keys().next().value!)
            }
            cache.set(key, { body, status: 200, expires: Date.now() + revalidate * 1000 })
            return new Response(body, { status: 200, headers: res.headers })
          }
          return res
        })
        if (pageMod.actions) {
          app.post(path, async (ctx: any) => {
            const denied = await guard(seg, ctx)
            if (denied) return denied
            const name = new URL(ctx.request.url).search.match(/^\?\/([\w-]+)/)?.[1] ?? 'default'
            // own keys only: ?/constructor or ?/toString must not reach Object.prototype
            const action = Object.hasOwn(pageMod.actions, name) ? pageMod.actions[name] : undefined
            if (typeof action !== 'function') throw new HttpError(404, `No action "${name}" on ${seg.path}`)
            const data = ctx.body instanceof FormData ? formToObject(ctx.body) : ctx.body
            const result = await als.run(makeStore(ctx, fixParams(seg, ctx.params)), () => action(data, ctx))
            if (result instanceof Response) return result
            // '//evil.example' as a path would be an open redirect, so leading slashes collapse to one
            if (result === undefined) return new Response(null, { status: 303, headers: { location: '/' + ctx.path.replace(/^[\/\\]+/, '') } })
            return render(seg, ctx, { actionData: result })
          })
        }
      }
    }
  }

  // SEO: sitemap of every static page, robots.txt pointing to it (a public/robots.txt wins)
  const staticPages = segments.filter((sg) => sg.files.page && !/[:*]/.test(sg.path)).map((sg) => sg.path)
  app.get('/sitemap.xml', ({ request }: any) => {
    const base = siteUrl || new URL(request.url).origin
    const urls = staticPages.flatMap((p) => (options.locales?.length ? options.locales.map((l, i) => (i === 0 ? p : `/${l}${p === '/' ? '' : p}`)) : [p]))
    const body = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls.map((u) => `<url><loc>${base}${u}</loc></url>`).join('')}</urlset>\n`
    return new Response(body, { headers: { 'content-type': 'application/xml; charset=utf-8', 'cache-control': 'public, max-age=3600' } })
  }, { detail: { hide: true } })
  app.get('/robots.txt', ({ request }: any) => {
    const base = siteUrl || new URL(request.url).origin
    return new Response(`User-agent: *\nAllow: /\nDisallow: /admin\nDisallow: /_raiko\n\nSitemap: ${base}/sitemap.xml\n`, { headers: { 'content-type': 'text/plain; charset=utf-8' } })
  }, { detail: { hide: true } })

  /** Enforce `auth` and `roles` exports. Returns a response when the user may not see the page. */
  async function guard(seg: Segment, ctx: any): Promise<Response | null> {
    const rule = ruleFor(seg)
    if (!rule.auth) {
      if (options.getUser) await userOf(ctx)
      return null
    }
    const u = await userOf(ctx)
    if (!u) return renderError(new HttpError(401), seg, ctx)
    if (!allowed(u, rule.roles)) return renderError(new HttpError(403), seg, ctx)
    return null
  }

  async function renderNotFound(ctx: any): Promise<Response> {
    const nf = root.files['not-found']
    if (!nf) return new Response(defaultNotFound(), { status: 404, headers: { 'content-type': 'text/html; charset=utf-8' } })
    return render(root, ctx, {}, { file: nf, status: 404 })
  }

  app.notFound(async ({ request, path }) => {
    const { BaseContext: C } = await import('../context')
    return renderNotFound(new C(request, path, '', {}))
  })

  return app
}

const A11Y_SCRIPT = '<script src="https://cdn.jsdelivr.net/npm/a11ymedic@0.2.0/dist/a11ymedic.js" data-button defer></script>'

const shell = (title: string, body: string) =>
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title}</title><style>body{margin:0;min-height:100vh;display:grid;place-items:center;background:#0a0a0b;color:#ededed;font:15px/1.5 ui-sans-serif,system-ui,sans-serif}main{text-align:center}h1{font-size:20px;font-weight:600;display:inline-block;padding-right:20px;margin-right:20px;border-right:1px solid #333}p{display:inline-block;color:#a1a1aa}</style></head><body><main>${body}</main></body></html>`

const defaultNotFound = () => shell('404: This page could not be found', '<h1>404</h1><p>This page could not be found.</p>')
const defaultError = () => shell('500: Something went wrong', '<h1>500</h1><p>Something went wrong on our side.</p>')
