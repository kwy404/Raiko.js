#!/usr/bin/env node
// raiko: dev, build, start, deploy, secret, routes, manifest
import { spawn, spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync, watch, readFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { randomBytes } from 'node:crypto'

const [cmd = 'help', ...args] = process.argv.slice(2)
const cwd = process.cwd()
// load .env into the environment of child processes (Bun does this on its own, Node does not)
if (existsSync(join(cwd, '.env')) && ['dev', 'start', 'build', 'routes'].includes(cmd)) {
  for (const line of readFileSync(join(cwd, '.env'), 'utf8').split('\n')) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line)
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2')
  }
}
const c = (n, s) => (process.stdout.isTTY ? `\x1b[${n}m${s}\x1b[0m` : s)
const y = (s) => c('33', s), dim = (s) => c('2', s), red = (s) => c('31', s), green = (s) => c('32', s)
const hasBun = () => !!process.versions.bun || spawnSync('bun', ['--version'], { stdio: 'ignore' }).status === 0
const flag = (name, def) => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? def : args[i + 1] ?? true
}
const entry = () => args.find((a) => !a.startsWith('--') && /\.(t|j)sx?$/.test(a)) ?? ['server.ts', 'server/index.ts', 'src/server.ts'].find((f) => existsSync(join(cwd, f))) ?? 'server.ts'
const pkg = existsSync(join(cwd, 'package.json')) ? JSON.parse(readFileSync(join(cwd, 'package.json'), 'utf8')) : {}

const SPECIAL = /^(page|layout|loading|error|not-found|forbidden|unauthorized|route|socket)\.(tsx|ts|jsx|js)$/
function manifest() {
  const dir = resolve(cwd, flag('dir', 'app'))
  const outDir = join(cwd, '.raiko')
  mkdirSync(outDir, { recursive: true })
  const files = []
  const walk = (abs) => {
    if (!existsSync(abs)) return
    for (const f of readdirSync(abs)) {
      if (f.startsWith('.') || f === 'node_modules') continue
      const p = join(abs, f)
      if (statSync(p).isDirectory()) walk(p)
      else if (SPECIAL.test(f)) files.push(relative(dir, p).split('\\').join('/'))
    }
  }
  walk(dir)
  for (const mw of ['middleware.ts', '../middleware.ts']) if (existsSync(join(dir, mw))) files.push(mw)
  const rel = (f) => './' + relative(outDir, join(dir, f)).split('\\').join('/').replace(/\.(tsx|ts|jsx|js)$/, '')
  const spec = (f) => (rel(f).startsWith('./..') ? rel(f).slice(2) : rel(f))
  const src = `// generated by raiko, do not edit\n${files.map((f, i) => `import * as m${i} from ${JSON.stringify(spec(f))}`).join('\n')}\n\nexport default {\n${files.map((f, i) => `  ${JSON.stringify(f)}: m${i},`).join('\n')}\n}\n`
  writeFileSync(join(outDir, 'manifest.ts'), src)
  return files.length
}

function run(bin, a, env = {}) {
  // no shell: arguments are never interpreted; on Windows the .cmd shims are called by name
  const exe = process.platform === 'win32' && ['npx', 'npm', 'bunx'].includes(bin) ? `${bin}.cmd` : bin
  const p = spawn(exe, a, { stdio: 'inherit', env: { ...process.env, ...env } })
  p.on('exit', (code) => process.exit(code ?? 0))
  return p
}

const banner = () => console.log(`\n  ${y('raiko')}${dim('.js')} ${dim(pkg.dependencies?.['raiko.js'] ?? '')}\n`)

switch (cmd) {
  case 'manifest': {
    console.log(`${green('ok')} manifest with ${manifest()} files`)
    break
  }
  case 'dev': {
    banner()
    if (existsSync(join(cwd, 'app'))) {
      manifest()
      try {
        watch(join(cwd, 'app'), { recursive: true }, (_, f) => f && SPECIAL.test(String(f).split(/[\\/]/).pop()) && manifest())
      } catch {}
    }
    const vite = ['vite.config.ts', 'vite.config.js', 'vite.config.mts'].some((f) => existsSync(join(cwd, f)))
    if (vite) run('npx', ['vite', ...args.filter((a) => a.startsWith('--'))], { NODE_ENV: 'development' })
    else if (hasBun()) run('bun', ['--watch', entry()], { NODE_ENV: 'development' })
    else run('npx', ['tsx', 'watch', entry()], { NODE_ENV: 'development' })
    break
  }
  case 'build': {
    banner()
    const t0 = Date.now()
    if (existsSync(join(cwd, 'app'))) console.log(`${green('ok')} routes manifest, ${manifest()} files`)
    const vite = ['vite.config.ts', 'vite.config.js', 'vite.config.mts'].some((f) => existsSync(join(cwd, f)))
    if (vite) {
      const r = spawnSync('npx', ['vite', 'build'], { stdio: 'inherit', env: { ...process.env, NODE_ENV: 'production' } })
      if (r.status) process.exit(r.status)
      console.log(`${green('ok')} frontend built, minified and mangled, no source maps`)
    }
    const out = join(cwd, '.raiko', 'out')
    const target = flag('target', hasBun() ? 'bun' : 'node')
    const r = hasBun()
      ? spawnSync('bun', ['build', entry(), '--target', target === 'bun' ? 'bun' : 'node', '--outdir', out, '--minify', '--packages', 'external'], { stdio: 'inherit' })
      : spawnSync('npx', ['esbuild', entry(), '--bundle', '--platform=node', '--format=esm', '--minify', '--packages=external', `--outdir=${out}`, '--jsx=automatic', '--jsx-import-source=raiko.js'], { stdio: 'inherit' })
    if (r.status) process.exit(r.status)
    console.log(`${green('ok')} server bundled to .raiko/out ${dim(`(${Date.now() - t0}ms)`)}\n\n  start it with ${y('raiko start')}\n`)
    break
  }
  case 'start': {
    const file = ['server.js', 'index.js'].map((f) => join(cwd, '.raiko', 'out', f)).find(existsSync)
    if (!file) {
      console.error(`${red('error[RK0701]')}: no build found\n  = help: run ${y('raiko build')} first`)
      process.exit(1)
    }
    run(hasBun() ? 'bun' : 'node', [file], { NODE_ENV: 'production' })
    break
  }
  case 'deploy': {
    const to = args.find((a) => !a.startsWith('--')) ?? pkg.raiko?.deploy ?? (existsSync(join(cwd, 'vercel.json')) ? 'vercel' : existsSync(join(cwd, 'wrangler.toml')) ? 'cloudflare' : existsSync(join(cwd, 'Dockerfile')) ? 'docker' : null)
    if (!to) {
      console.error(`${red('error[RK0702]')}: no deploy target found\n  = help: raiko deploy vercel | cloudflare | docker`)
      process.exit(1)
    }
    console.log(`\n  deploying to ${y(to)}\n`)
    if (to === 'vercel') run('npx', ['vercel', '--prod'])
    else if (to === 'cloudflare') run('npx', ['wrangler', 'deploy'])
    else if (to === 'docker') run('docker', ['build', '-t', pkg.name ?? 'raiko-app', '.'])
    else {
      console.error(`${red('error[RK0703]')}: unknown target "${to}"`)
      process.exit(1)
    }
    break
  }
  case 'secret': {
    console.log(randomBytes(48).toString('base64url'))
    break
  }
  case 'routes': {
    const runner = hasBun() ? ['bun', ['-e', `const m = await import(${JSON.stringify(resolve(entry()))}); const a = m.default ?? m.app; a.compile?.(); for (const r of a.routes) console.log(r.method.padEnd(7), r.path)`]] : null
    if (!runner) {
      console.error('raiko routes needs Bun for now: bunx raiko routes')
      process.exit(1)
    }
    run(...runner)
    break
  }
  default:
    console.log(`
  ${y('raiko')}${dim('.js')}

  raiko dev [entry]        start the dev server with reload
  raiko build              build frontend and bundle the server
  raiko start              run the production build
  raiko deploy [target]    vercel, cloudflare or docker
  raiko routes             list every route
  raiko secret             print a random secret for AUTH_SECRET
  raiko manifest           write .raiko/manifest.ts for serverless hosts
`)
}
