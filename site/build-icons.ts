// Renders every site icon to inline SVG with glyphfox at build time: no icon script in the browser.
import { toSvg, getIcon } from 'glyphfox'
import { readFileSync, writeFileSync } from 'node:fs'

const FEATURES = ['folder', 'server', 'braces', 'wifi', 'lock', 'grid', 'mail', 'triangle-alert', 'layers', 'shield', 'search', 'check']
for (const n of [...FEATURES, 'sun', 'brand-github']) if (!getIcon(n)) throw new Error(`unknown glyphfox icon: ${n}`)
const svg = (n: string, size: number) => toSvg(n, { size, color: 'currentColor' })
writeFileSync(new URL('./icons.js', import.meta.url), `// generated by build-icons.ts\nwindow.RK_ICONS = ${JSON.stringify(FEATURES.map((n) => svg(n, 18)))}\n`)

const file = new URL('./index.html', import.meta.url)
let html = readFileSync(file, 'utf8')
html = html.replace(/<glyph-fox name="([\w-]+)" size="(\d+)"><\/glyph-fox>/g, (_, n, s) => svg(n, Number(s)))
writeFileSync(file, html)
console.log('icons ok')
